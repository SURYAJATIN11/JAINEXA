const STUDENTS_STORAGE_KEY = "campus_ledger_registered_students_v2";

export function loadAllStudents(): Student[] {
  try {
    const raw = localStorage.getItem(STUDENTS_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error("Failed to load students from localStorage", e);
  }
  return CSE_GEN_SECTION_F_STUDENTS;
}

export function saveAllStudents(students: Student[]): void {
  try {
    localStorage.setItem(STUDENTS_STORAGE_KEY, JSON.stringify(students));
    window.dispatchEvent(new CustomEvent("campus_ledger_students_updated", { detail: students }));
  } catch (e) {
    console.error("Failed to save students to localStorage", e);
  }
}

export function addStudentRecord(newStudent: Student): { success: boolean; student: Student; error?: string } {
  const current = loadAllStudents();
  const normUSN = newStudent.usn.toUpperCase().trim();
  const existing = current.find((s) => s.usn.toUpperCase().trim() === normUSN);
  if (existing) {
    return { success: false, student: existing, error: `Student with USN ${newStudent.usn} already exists.` };
  }
  const cleanStudent: Student = {
    ...newStudent,
    usn: normUSN,
    sNo: current.length + 1,
    name: newStudent.name.toUpperCase().trim()
  };
  const updated = [...current, cleanStudent];
  saveAllStudents(updated);
  return { success: true, student: cleanStudent };
}

export function removeStudentRecord(usnOrName: string): { success: boolean; removedStudent?: Student; error?: string } {
  const current = loadAllStudents();
  const norm = usnOrName.toUpperCase().trim();
  const target = current.find(
    (s) => s.usn.toUpperCase().trim() === norm || s.name.toUpperCase().includes(norm)
  );
  if (!target) {
    return { success: false, error: `No student record found matching "${usnOrName}".` };
  }
  const updated = current.filter((s) => s.usn !== target.usn);
  saveAllStudents(updated);
  return { success: true, removedStudent: target };
}

export function getStudentsForBatch(program: string = "CSE-GEN", semester: string = "3", section: string = "F"): Student[] {
  const normProg = (program || "").toUpperCase().trim();
  const normSem = String(semester || "").trim();
  const normSec = (section || "").toUpperCase().trim();

  const isCseGen = normProg === "CSE-GEN" || normProg === "CSE_GEN" || normProg === "CSE";
  const isSem3 = normSem === "3" || normSem === "3RD" || normSem === "SEM 3";
  const isSecF = normSec === "F" || normSec === "SECTION F" || normSec === "SEC F" || normSec.endsWith("-F") || normSec.endsWith(" F");

  const all = loadAllStudents();

  // If asking for CSE-GEN 3 F:
  if (isCseGen && isSem3 && isSecF) {
    return all.filter((s) => {
      const sProg = (s.program || "CSE-GEN").toUpperCase();
      const sSec = (s.section || "F").toUpperCase();
      return (sProg === "CSE-GEN" || sProg === "CSE") && s.semester === "3" && (sSec === "F" || sSec === "SEC F");
    });
  }

  // Other classes: return any custom students matching that batch, or generated roster
  const matchingCustom = all.filter((s) => {
    return s.program.toUpperCase() === normProg && s.semester === normSem && s.section.toUpperCase() === normSec;
  });

  if (matchingCustom.length > 0) {
    return matchingCustom;
  }

  // Distinct batch roster fallback:
  const defaultCount = 45;
  const list: Student[] = [];
  const progPrefix = (program || "CSE").substring(0, 3).toUpperCase();
  const semNum = normSem || "1";
  const secChar = normSec || "A";

  for (let i = 1; i <= defaultCount; i++) {
    const padded = String(i).padStart(3, "0");
    list.push({
      sNo: i,
      usn: `25BT${progPrefix}${padded}`,
      name: `Student ${padded} (${program} S${semNum} ${secChar})`,
      program: program || "CSE-GEN",
      semester: semNum,
      section: secChar
    });
  }
  return list;
}

export function getStudentRegisteredPhone(usn: string): string {
  const digits = usn.replace(/[^0-9]/g, "");
  const suffix = digits.slice(-3).padStart(3, "0");
  return `9845010${suffix}`;
}

export interface StudentAuthResult {
  success: boolean;
  student?: Student & { phone: string };
  error?: string;
}

export function findStudentByUsn(usnOrName: string): StudentAuthResult {
  const normInput = (usnOrName || "").trim().toUpperCase();
  if (!normInput) {
    return { success: false, error: "Please enter your University USN." };
  }

  const allStudents = loadAllStudents();

  // Match: Check by exact USN
  let match = allStudents.find((s) => s.usn.toUpperCase() === normInput);

  // Match by contains / prefix USN
  if (!match) {
    match = allStudents.find((s) => s.usn.toUpperCase().includes(normInput) || normInput.includes(s.usn.toUpperCase()));
  }

  // Fallback match by Name
  if (!match) {
    match = allStudents.find((s) => s.name.toUpperCase() === normInput);
  }

  if (!match) {
    match = allStudents.find((s) => {
      const sName = s.name.toUpperCase();
      if (sName.includes(normInput) || normInput.includes(sName)) return true;
      const inputWords = normInput.split(/\s+/).filter(Boolean);
      return inputWords.length >= 2 && inputWords.every((w) => sName.includes(w));
    });
  }

  if (!match) {
    return {
      success: false,
      error: `No registered student record found for USN "${usnOrName}". Please verify your University USN.`
    };
  }

  const expectedPhone = (match.phone || getStudentRegisteredPhone(match.usn)).replace(/[^0-9]/g, "").slice(-10);

  return {
    success: true,
    student: { ...match, phone: expectedPhone }
  };
}

export function findStudentByCredentials(phone: string, nameOrUsn: string): StudentAuthResult {
  const normInput = (nameOrUsn || "").trim().toUpperCase();
  const normPhone = (phone || "").replace(/[^0-9]/g, "").slice(-10);

  // If phone is not provided, authenticate via USN directly
  if (!normPhone || normPhone.length === 0) {
    return findStudentByUsn(nameOrUsn);
  }

  if (!normInput) {
    return { success: false, error: "Please enter your University USN." };
  }

  const allStudents = loadAllStudents();

  // Match: Check by USN first
  let match = allStudents.find(
    (s) => s.usn.toUpperCase() === normInput
  );

  // Check by full or partial Name if USN did not match
  if (!match) {
    match = allStudents.find(
      (s) => s.name.toUpperCase() === normInput
    );
  }

  if (!match) {
    match = allStudents.find((s) => {
      const sName = s.name.toUpperCase();
      if (sName.includes(normInput) || normInput.includes(sName)) return true;
      const inputWords = normInput.split(/\s+/).filter(Boolean);
      return inputWords.length >= 2 && inputWords.every((w) => sName.includes(w));
    });
  }

  if (!match) {
    return {
      success: false,
      error: `No registered student record found for "${nameOrUsn}". Please verify your registered USN.`
    };
  }

  // Exact registered phone number verification
  const expectedPhone = (match.phone || getStudentRegisteredPhone(match.usn)).replace(/[^0-9]/g, "").slice(-10);

  if (normPhone !== expectedPhone) {
    return {
      success: false,
      error: `Access Denied: The mobile number ending in ...${normPhone.slice(-4)} is NOT registered to ${match.name} (${match.usn}). Please use your registered phone number (ending in ...${expectedPhone.slice(-4)}).`
    };
  }

  return {
    success: true,
    student: { ...match, phone: expectedPhone }
  };
}

